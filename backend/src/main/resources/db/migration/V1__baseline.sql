-- ============================================================
-- V1: Baseline do schema do Portal Partners
--
-- Representa o schema completo que o Hibernate (ddl-auto=update)
-- gerava ate aqui. A partir desta versao, o schema passa a ser
-- gerenciado por Flyway e validado por ddl-auto=validate.
--
-- Script base extraido via geracao de DDL do Hibernate contra
-- PostgreSQL 16, acrescido dos indices/constraints adicionais que
-- as migrations V2-V4 introduziam (GIN em JSONB, indice unico
-- parcial de cpf_hash). As migrations V2-V4 permanecem idempotentes
-- (IF NOT EXISTS / IF EXISTS) para ambientes legados.
-- ============================================================

-- Extensao necessaria para gen_random_uuid() e, futuramente, backfill de hash.
CREATE EXTENSION IF NOT EXISTS pgcrypto;

create table if not exists usuario (
    must_change_password boolean,
    contratada_id bigint,
    contratante_id bigint,
    id bigint generated by default as identity,
    reset_token_expiration timestamp(6),
    email varchar(255) not null unique,
    nome varchar(255),
    reset_token varchar(255),
    role varchar(255) not null check (role in ('ADMIN','CONTRATADA','CONTRATANTE')),
    senha varchar(255) not null,
    primary key (id)
);

create table if not exists contratante (
    id bigint generated by default as identity,
    usuario_id bigint not null unique,
    cnpj varchar(255) unique,
    dominio_email varchar(255) unique,
    nome varchar(255) not null,
    primary key (id)
);

create table if not exists contratada (
    contratante_id bigint,
    id bigint generated by default as identity,
    usuario_id bigint not null unique,
    cnpj varchar(255) not null unique,
    nome varchar(255) not null,
    numero_contrato varchar(255) not null,
    numero_pedido varchar(255) not null,
    primary key (id)
);

create table if not exists contrato (
    contratada_id bigint not null,
    contratante_id bigint not null,
    id bigint generated by default as identity,
    numero_contrato varchar(255) not null,
    numero_pedido varchar(255) not null,
    primary key (id)
);

create table if not exists funcionario (
    contratada_id bigint,
    id bigint generated by default as identity,
    cpf varchar(255) not null,
    cpf_hash varchar(255) unique,
    nome_completo varchar(255) not null,
    primary key (id)
);

create table if not exists documento (
    contratada_id bigint,
    data_download_contratante timestamp(6),
    data_postagem timestamp(6) not null,
    data_status_atualizado timestamp(6),
    funcionario_id bigint,
    id bigint generated by default as identity,
    tamanho_bytes bigint,
    arquivo_path varchar(255),
    content_type varchar(255),
    nome_arquivo varchar(255) not null,
    nome_arquivo_original varchar(255),
    object_key varchar(255),
    status_documento varchar(255) check (status_documento in ('POSTADO','ANALISADO','APROVADO','PENDENTE','REPROVADO')),
    tipo_documento varchar(255) not null check (tipo_documento in ('CNPJ','PGR','PCMSO','ORDEM_SERVICO','CNDT','CNAT','CNRF','GRIP','CTPS_DIGITAL','INSS','FGTS','HOLERITE','ASO','RG','CPF','FICHA_EPI','NR10','NR12','NR35')),
    primary key (id)
);

create table if not exists evento_documento (
    data_hora timestamp(6) not null,
    documento_id bigint,
    id bigint generated by default as identity,
    evento varchar(255) not null,
    primary key (id)
);

create table if not exists download_token (
    marca_download_contratante boolean not null,
    consumido_em timestamp(6),
    criado_em timestamp(6) not null,
    documento_id bigint not null,
    expira_em timestamp(6) not null,
    id bigint generated by default as identity,
    usuario_id bigint not null,
    ip_consumo varchar(50),
    token varchar(64) not null unique,
    object_key varchar(255) not null,
    primary key (id)
);

create table if not exists lgpd_consent (
    timestamp timestamp(6) not null,
    user_id bigint not null,
    id uuid not null,
    versao_termo varchar(20) not null,
    ip varchar(50),
    user_agent varchar(500),
    hash_termo varchar(255),
    primary key (id)
);

create table if not exists audit_log (
    organizacao_id bigint,
    timestamp timestamp(6) not null,
    user_id bigint,
    id uuid not null,
    status varchar(20) not null check (status in ('SUCCESS','FAILURE')),
    ip varchar(50),
    role varchar(50),
    acao varchar(100) not null,
    entidade varchar(100),
    user_agent varchar(500),
    email varchar(255),
    entidade_id varchar(255),
    mensagem_erro TEXT,
    detalhes_json jsonb,
    primary key (id)
);

-- Indices gerados pelo Hibernate
create index if not exists idx_audit_log_timestamp_user on audit_log (timestamp, user_id);
create index if not exists idx_audit_log_organizacao on audit_log (organizacao_id, timestamp);
create index if not exists idx_audit_log_acao on audit_log (acao);
create index if not exists idx_audit_log_status on audit_log (status);
create index if not exists idx_download_token_expira on download_token (expira_em);
create index if not exists idx_lgpd_consent_user_versao on lgpd_consent (user_id, versao_termo);

-- Indice GIN para queries JSON nativas no campo JSONB (vinha da V2)
create index if not exists idx_audit_log_detalhes_gin on audit_log using gin (detalhes_json);

-- Indice unico parcial de cpf_hash (vinha da V4)
create unique index if not exists idx_funcionario_cpf_hash_unique
    on funcionario (cpf_hash) where cpf_hash is not null;

-- Foreign keys (idempotentes: so adiciona se ainda nao existir a constraint nomeada).
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_contratada_contratante') THEN
        ALTER TABLE contratada ADD CONSTRAINT fk_contratada_contratante FOREIGN KEY (contratante_id) REFERENCES contratante;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_contratada_usuario') THEN
        ALTER TABLE contratada ADD CONSTRAINT fk_contratada_usuario FOREIGN KEY (usuario_id) REFERENCES usuario;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_contratante_usuario') THEN
        ALTER TABLE contratante ADD CONSTRAINT fk_contratante_usuario FOREIGN KEY (usuario_id) REFERENCES usuario;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_contrato_contratada') THEN
        ALTER TABLE contrato ADD CONSTRAINT fk_contrato_contratada FOREIGN KEY (contratada_id) REFERENCES contratada;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_contrato_contratante') THEN
        ALTER TABLE contrato ADD CONSTRAINT fk_contrato_contratante FOREIGN KEY (contratante_id) REFERENCES contratante;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_documento_contratada') THEN
        ALTER TABLE documento ADD CONSTRAINT fk_documento_contratada FOREIGN KEY (contratada_id) REFERENCES contratada;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_documento_funcionario') THEN
        ALTER TABLE documento ADD CONSTRAINT fk_documento_funcionario FOREIGN KEY (funcionario_id) REFERENCES funcionario;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_evento_documento') THEN
        ALTER TABLE evento_documento ADD CONSTRAINT fk_evento_documento FOREIGN KEY (documento_id) REFERENCES documento;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_funcionario_contratada') THEN
        ALTER TABLE funcionario ADD CONSTRAINT fk_funcionario_contratada FOREIGN KEY (contratada_id) REFERENCES contratada;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_usuario_contratada') THEN
        ALTER TABLE usuario ADD CONSTRAINT fk_usuario_contratada FOREIGN KEY (contratada_id) REFERENCES contratada;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_usuario_contratante') THEN
        ALTER TABLE usuario ADD CONSTRAINT fk_usuario_contratante FOREIGN KEY (contratante_id) REFERENCES contratante;
    END IF;
END $$;
